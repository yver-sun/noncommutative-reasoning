"""
5 Prompt Strategies × 3 Symbol Conditions = 15 prompt configurations.

Strategies:
1. Zero-Shot (ZS): Axioms + direct question, no guidance
2. Chain-of-Thought (CoT): Step-by-step reasoning guidance
3. CoT + Self-Consistency @16 (CoT+SC@16): CoT with majority voting
4. CoT + Program-of-Thought (CoT+PoT): Code-style algebraic reasoning
5. CoT + Self-Verify (CoT+Self-Verify): CoT + explicit verification step

Each strategy adapts to 3 symbol conditions (Standard, Abstract, Random).

Ref: research_design.tex §4
"""

from dataclasses import dataclass
from typing import Literal

from .probes import (
    Probe, PROBE_LADDER,
    get_symbols, get_metric_str, get_ground_truth, get_question,
)

Strategy = Literal["zs", "cot", "cot_sc", "cot_pot", "cot_sv"]
Condition = Literal["standard", "abstract", "random"]


@dataclass
class PromptBundle:
    """Complete set of prompts for one experiment instance."""
    system_prompt: str
    user_prompt: str
    strategy: Strategy
    condition: Condition
    probe_level: int


# ═══════════════════════════════════════════════════════════════════════════════
# System Prompt Generator (Axiom Definition)
# ═══════════════════════════════════════════════════════════════════════════════

def build_system_prompt(condition: Condition, metric: dict[int, int],
                        symbols: dict[int, str]) -> str:
    """Build the absolute axiom system for A(Σ).

    This prompt severs all pre-trained geometric algebra associations.
    """
    dim = len(metric)
    basis_list = ", ".join(symbols[i] for i in range(1, dim + 1))
    lam_lines = "\n".join(f"- Λ({i}) = {v}" for i, v in sorted(metric.items()))

    if condition == "standard":
        return f"""You are working with Clifford algebra Cl(p,q). Follow these rules precisely:

Rule 1 (Basis): The algebra is generated by orthogonal basis vectors {{{basis_list}}}.

Rule 2 (Anti-commutation): For i ≠ j, e_i * e_j = -e_j * e_i.

Rule 3 (Metric): e_i * e_i = η_ii. Current metric:
{lam_lines}

Rule 4 (Distribution): Products expand by distribution while preserving left-right order.

Rule 5 (Associativity): (a * b) * c = a * (b * c).

IMPORTANT: Show your complete derivation. Output your final answer in a clearly marked section."""

    elif condition == "abstract":
        return f"""You are an abstract logical deduction engine. Discard ALL conventional algebra rules. Follow ONLY these five axioms:

Axiom 1 (Elements): The system consists of discrete atomic states {{{basis_list}}} and real scalar coefficients.

Axiom 2 (Fusion): The operator (*) is associative but STRICTLY non-commutative: ω_i * ω_j ≠ ω_j * ω_i for i ≠ j.

Axiom 3 (Parity Inversion): Swapping order of two distinct atomic states introduces a sign reversal: a(ω_i * ω_j) = -a(ω_j * ω_i).

Axiom 4 (Auto-Collapse): Identical states collapse to a scalar: ω_i * ω_i = Λ(i).

Axiom 5 (Distribution): (Σ a_i ω_i) * (Σ b_j ω_j) expands by distributing while preserving left-right order.

Current metric:
{lam_lines}

IMPORTANT: Show your complete derivation. Output your final answer in a clearly marked section."""

    else:  # random
        return f"""You are an abstract logical engine. The system uses NOVEL symbols with absolutely no pre-existing mathematical meaning.

Symbols: {{{basis_list}}}

Axiom 1: The system consists of these abstract symbols and real scalar coefficients.

Axiom 2: The operator (*) is associative but STRICTLY non-commutative.

Axiom 3: Swapping order of two distinct symbols introduces a sign reversal: a(S_i * S_j) = -a(S_j * S_i).

Axiom 4: Identical symbols collapse: S_i * S_i = Λ(i).

Axiom 5: (Σ a_i S_i) * (Σ b_j S_j) expands by distribution.

Current metric:
{lam_lines}

IMPORTANT: Show your complete derivation. Output your final answer in a clearly marked section."""


# ═══════════════════════════════════════════════════════════════════════════════
# Strategy 1: Zero-Shot (ZS)
# ═══════════════════════════════════════════════════════════════════════════════

def zero_shot_prompt(probe: Probe, condition: Condition,
                     metric: dict[int, int]) -> PromptBundle:
    """Zero-shot: axioms only, direct question, no reasoning guidance."""
    dim = len(metric)
    symbols = get_symbols(condition, max(dim, 4))
    system = build_system_prompt(condition, metric, symbols)
    question = get_question(probe, condition, symbols, metric)

    user = f"""{question}

Output your final answer clearly as: FINAL ANSWER: <your answer>"""

    return PromptBundle(
        system_prompt=system,
        user_prompt=user,
        strategy="zs",
        condition=condition,
        probe_level=probe.level,
    )


# ═══════════════════════════════════════════════════════════════════════════════
# Strategy 2: Chain-of-Thought (CoT)
# ═══════════════════════════════════════════════════════════════════════════════

def cot_prompt(probe: Probe, condition: Condition,
               metric: dict[int, int]) -> PromptBundle:
    """CoT: guided step-by-step reasoning with explicit step labels."""
    dim = len(metric)
    symbols = get_symbols(condition, max(dim, 4))
    system = build_system_prompt(condition, metric, symbols)
    question = get_question(probe, condition, symbols, metric)

    user = f"""{question}

Please solve this step-by-step. For each step:
1. State what axiom or rule you are applying.
2. Show the intermediate expression after applying the rule.
3. Verify the expression is correct before proceeding.

At the end, clearly state: FINAL ANSWER: <your answer>"""

    return PromptBundle(
        system_prompt=system,
        user_prompt=user,
        strategy="cot",
        condition=condition,
        probe_level=probe.level,
    )


# ═══════════════════════════════════════════════════════════════════════════════
# Strategy 3: CoT + Self-Consistency @16 (CoT+SC@16)
# ═══════════════════════════════════════════════════════════════════════════════

def cot_sc_prompt(probe: Probe, condition: Condition,
                  metric: dict[int, int]) -> PromptBundle:
    """
    CoT+SC@16: Same as CoT but designed for self-consistency.
    We run the same CoT prompt 16 times and take the majority answer.
    Temperature is set to 0.7 for diversity in SC runs.
    """
    dim = len(metric)
    symbols = get_symbols(condition, max(dim, 4))
    system = build_system_prompt(condition, metric, symbols)
    question = get_question(probe, condition, symbols, metric)

    user = f"""{question}

Think through this problem carefully, step by step. Consider multiple approaches.
At the end, clearly state: FINAL ANSWER: <your answer>"""

    return PromptBundle(
        system_prompt=system,
        user_prompt=user,
        strategy="cot_sc",
        condition=condition,
        probe_level=probe.level,
    )


# ═══════════════════════════════════════════════════════════════════════════════
# Strategy 4: CoT + Program-of-Thought (CoT+PoT)
# ═══════════════════════════════════════════════════════════════════════════════

def cot_pot_prompt(probe: Probe, condition: Condition,
                   metric: dict[int, int]) -> PromptBundle:
    """
    CoT+PoT: Code-style algebraic reasoning.
    Model is asked to write out algebraic steps as structured "code".
    """
    dim = len(metric)
    symbols = get_symbols(condition, max(dim, 4))
    system = build_system_prompt(condition, metric, symbols)
    question = get_question(probe, condition, symbols, metric)

    user = f"""{question}

Solve this using algebraic program-of-thought. Write each step as a structured transformation:

```
STEP 1: [Operation: e.g., EXPAND]
  Input: <expression before>
  Rule: <which axiom>
  Output: <expression after>

STEP 2: [Operation: e.g., SWAP e3,e1]
  Input: <expression before>
  Rule: Axiom 3 (Parity Inversion): a*e3*e1 = -a*e1*e3
  Output: <expression after, with sign adjustment>

... continue for all steps ...

FINAL RESULT: <simplified expression>
```

Be precise with signs. Track every parity inversion carefully."""

    return PromptBundle(
        system_prompt=system,
        user_prompt=user,
        strategy="cot_pot",
        condition=condition,
        probe_level=probe.level,
    )


# ═══════════════════════════════════════════════════════════════════════════════
# Strategy 5: CoT + Self-Verify (CoT+Self-Verify)
# ═══════════════════════════════════════════════════════════════════════════════

def cot_sv_prompt(probe: Probe, condition: Condition,
                  metric: dict[int, int]) -> PromptBundle:
    """
    CoT+Self-Verify: CoT + explicit verification step.
    Model must derive AND THEN independently verify its answer.
    """
    dim = len(metric)
    symbols = get_symbols(condition, max(dim, 4))
    system = build_system_prompt(condition, metric, symbols)
    question = get_question(probe, condition, symbols, metric)

    user = f"""{question}

PHASE 1 — DERIVATION:
Solve this problem step-by-step, applying the axioms carefully.

PHASE 2 — VERIFICATION:
Now, independently verify your answer using a DIFFERENT approach:

1. Re-derive from scratch using a different order of operations.
2. Check that every parity inversion (swap) has the correct sign.
3. Check that every auto-collapse uses the correct Λ(i) value.
4. If the two derivations agree, confirm your answer.
5. If they disagree, identify the error and correct it.

FINAL ANSWER: <your verified answer>"""

    return PromptBundle(
        system_prompt=system,
        user_prompt=user,
        strategy="cot_sv",
        condition=condition,
        probe_level=probe.level,
    )


# ═══════════════════════════════════════════════════════════════════════════════
# Strategy Dispatch
# ═══════════════════════════════════════════════════════════════════════════════

STRATEGY_BUILDERS = {
    "zs": zero_shot_prompt,
    "cot": cot_prompt,
    "cot_sc": cot_sc_prompt,
    "cot_pot": cot_pot_prompt,
    "cot_sv": cot_sv_prompt,
}


def build_prompt(probe: Probe, strategy: Strategy, condition: Condition,
                 metric: dict[int, int]) -> PromptBundle:
    """Build a complete prompt bundle for one experiment instance."""
    builder = STRATEGY_BUILDERS[strategy]
    return builder(probe, condition, metric)
